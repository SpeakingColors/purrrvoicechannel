#!/usr/bin/env python3
"""Reads the faceplate layout of the mockup (docs/mockup/index.html) and writes what the JUCE editor needs:
  assets/ui/faceplate.png   the static faceplate at 2x (labels, scales, panels, wood), with every live part hidden
  src/ui/LayoutGen.h        the position of every control, display and readout, in mockup pixels (2200 x 960)
The editor draws the live parts (knobs, LEDs, switches, displays, meters, values) natively on top, so the plugin
window is the mockup. Run after every mockup change:  python3 tools/extract_layout.py   (needs playwright + chromium)"""
import json, os, sys
from playwright.sync_api import sync_playwright
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = "file://" + os.path.join(root, "docs/mockup/index.html") + "?shot=1"
JS_IDS = r"""() => {
  const win = document.querySelector('#win'), W = win.getBoundingClientRect();
  const R = (e) => { const r = e.getBoundingClientRect(); return [Math.round(r.left - W.left), Math.round(r.top - W.top), Math.round(r.width), Math.round(r.height)]; };
  const vis = (e) => { const r = e.getBoundingClientRect(); return r.width > 2 && r.height > 2 && getComputedStyle(e).visibility !== 'hidden'; };
  const rec = []; const orig = window.setParam; window.setParam = function (id) { rec.push(id); return orig.apply(this, arguments); };
  const out = { win: [Math.round(W.width), Math.round(W.height)], knobs: [], leds: [], sws: [], el: {} };
  document.querySelectorAll('.kw').forEach((w) => { const k = w.querySelector('.knob'); if (!k || !vis(k)) return; rec.length = 0;
    k.dispatchEvent(new MouseEvent('dblclick', { bubbles: true })); if (!rec.length) return;
    const val = w.querySelector('.val'), kv = w.querySelector('.kv');
    out.knobs.push({ id: rec[0], r: R(k), v: kv ? R(kv) : null, col: val ? getComputedStyle(val).stroke : '', big: w.classList.contains('big') }); });
  document.querySelectorAll('button.ledb, button.pb').forEach((b) => { if (!vis(b) || b.closest('.rig') || b.closest('.sw')) return; rec.length = 0; b.click(); if (!rec.length) return; b.click();
    out.leds.push({ id: rec[0], r: R(b), mini: b.classList.contains('mini'), txt: b.textContent.trim() }); });
  document.querySelectorAll('.sw').forEach((s) => { const b = s.querySelector('button.ledb'); if (!b || !vis(b)) return; rec.length = 0; b.click(); if (!rec.length) return; b.click();
    const l = s.querySelector('.l u'), r = s.querySelector('.r u');
    out.sws.push({ id: rec[0], r: R(b), lu: l ? R(l) : null, ru: r ? R(r) : null, lt: R(s.querySelector('.l em')), rt: R(s.querySelector('.r em')), ls: s.querySelector('.l em').textContent, rs: s.querySelector('.r em').textContent }); });
  window.setParam = orig;
  const ids = ['pPrev', 'pName', 'pNext', 'pSave', 'pMore', 'bHelp', 'bSet', 'bAbout', 'disp', 'cvGR', 'cvVU', 'cvM', 'ro', 'gTot', 'tRate', 'tDots', 'settleB', 'settleT', 'sizeT', 'cvGT', 'hint'];
  ids.forEach((i) => { const e = document.getElementById(i); if (e && vis(e)) out.el[i] = R(e); });
  const sel = document.getElementById('tubeSel'); if (sel) out.el.tubeSel = R(sel);
  const ft = document.querySelector('.foot>span'); if (ft) out.el.foot = R(ft);

  const tl = document.getElementById('tLine'); if (tl) out.el.tLine = R(tl);
  out.tabs = [...document.querySelectorAll('[data-view]')].filter(vis).map((t) => ({ v: t.dataset.view, r: R(t) }));
  return out; }"""
HIDE = """.knob,.kv,.ledb,button.pb,.sw u,canvas,#ro,#gTot,#tRate,#tDots,#settleB,#settleT,#sizeT,#tubeSel,#tLine,#pNameT,#hint,.tick{visibility:hidden!important}
.sw .l em,.sw .r em{visibility:hidden!important}.foot>span:first-child{visibility:hidden!important}"""
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 2400, "height": 1200}, device_scale_factor=2)
    pg.goto(URL); pg.wait_for_timeout(1500)
    L = pg.evaluate(JS_IDS)
    for t in L["tabs"]: pass
    pg.add_style_tag(content=HIDE)
    pg.evaluate("() => document.querySelectorAll('[data-view]').forEach(t => t.setAttribute('aria-pressed', 'false'))")
    pg.wait_for_timeout(300)
    pg.locator("#win").screenshot(path=os.path.join(root, "assets/ui/faceplate.png"))
    b.close()
json.dump(L, open("/tmp/pvc_layout.json", "w"), indent=1)
def r4(r): return "{ %d, %d, %d, %d }" % tuple(r) if r else "{ 0, 0, 0, 0 }"
o = ["// generated by tools/extract_layout.py from docs/mockup/index.html, do not edit by hand", "#pragma once", "namespace pvc::layout {",
     "struct R { int x, y, w, h; };", "constexpr int W = %d, H = %d;" % tuple(L["win"]),
     "struct Knob { const char* id; R r, v; unsigned col; bool big; };", "struct Led { const char* id; R r; bool mini; const char* txt; };",
     "struct Sw { const char* id; R r, lu, ru; };", "struct Tab { const char* v; R r; };"]
o.append("inline const char* swText[][2] = {"); o += ['    { %s, %s },' % (json.dumps(x["ls"]), json.dumps(x["rs"])) for x in L["sws"]]; o.append("};")
def col(s):
    import re; m = re.findall(r"[\d.]+", s or "")
    return "0xff%02x%02x%02x" % tuple(int(float(x)) for x in m[:3]) if len(m) >= 3 else "0xff02ebba"
o.append("inline const Knob knobs[] = {"); o += ['    { "%s", %s, %s, %s, %s },' % (k["id"], r4(k["r"]), r4(k["v"]), col(k["col"]), "true" if k["big"] else "false") for k in L["knobs"]]; o.append("};")
o.append("inline const Led leds[] = {"); o += ['    { "%s", %s, %s, %s },' % (l["id"], r4(l["r"]), "true" if l["mini"] else "false", json.dumps(l["txt"])) for l in L["leds"]]; o.append("};")
o.append("inline const Sw sws[] = {"); o += ['    { "%s", %s, %s, %s },' % (s["id"], r4(s["r"]), r4(s["lu"]), r4(s["ru"])) for s in L["sws"]]; o.append("};")
o.append("inline const R swLabels[][2] = {"); o += ['    { %s, %s },' % (r4(x["lt"]), r4(x["rt"])) for x in L["sws"]]; o.append("};")
o.append("inline const Tab tabs[] = {"); o += ['    { "%s", %s },' % (t["v"], r4(t["r"])) for t in L["tabs"]]; o.append("};")
for k, v in L["el"].items(): o.append("constexpr R %s = %s;" % (k, r4(v)))
o.append("}"); open(os.path.join(root, "src/ui/LayoutGen.h"), "w").write("\n".join(o) + "\n")
print(len(L["knobs"]), "knobs", len(L["leds"]), "leds", len(L["sws"]), "switches", len(L["tabs"]), "tabs", sorted(L["el"]))
